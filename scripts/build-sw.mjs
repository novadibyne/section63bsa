// Writes out/sw.js after `next build`: a service worker that lets the app run with no internet at all.
// Pages, scripts and styles are cached on the first visit; fonts and the scan engines are cached the
// first time they are used. Nothing is ever sent anywhere: the worker only reads files of this site.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'out');
const PRECACHE_EXT = /\.(html|txt|js|css|svg|json|ico|webmanifest)$/;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash('sha256');
const urls = [];
for (const file of walk(out).sort()) {
  const rel = relative(out, file).split(sep).join('/');
  if (rel === 'sw.js' || rel.startsWith('vendor/') || !PRECACHE_EXT.test(rel)) continue;
  hash.update(rel).update(readFileSync(file));
  // trailingSlash: true serves x/index.html at x/; the root page is "./".
  urls.push(rel === 'index.html' ? './' : rel.endsWith('/index.html') ? rel.slice(0, -'index.html'.length) : rel);
}
const version = hash.digest('hex').slice(0, 16);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(urls)};
const APP_CACHE = 'app-' + VERSION;
const RUNTIME_CACHE = 'runtime';
const scope = self.registration.scope;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(APP_CACHE).then((c) => c.addAll(PRECACHE.map((u) => new URL(u, scope)))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('app-') && k !== APP_CACHE).map((k) => caches.delete(k)))),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || !req.url.startsWith(scope)) return;

  // Pages: try the network for the newest version, fall back to the cached copy when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(async () => (await caches.match(req, { ignoreSearch: true })) ?? (await caches.match(new URL('./', scope)))),
    );
    return;
  }

  // Everything else: cached copy first; fonts and scan engines are cached the first time they load.
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ??
        fetch(req).then((res) => {
          if (res.ok && /\\/(vendor|_next\\/static\\/media)\\//.test(req.url)) {
            const copy = res.clone();
            caches.open(RUNTIME_CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;

writeFileSync(join(out, 'sw.js'), sw);
console.log(`build-sw: ${urls.length} files precached, version ${version}`);
